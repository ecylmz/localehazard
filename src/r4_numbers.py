"""Macros of the paper that come from the emulated drift experiment (dbms/results).

Writes OUTDIR/numbers_r4.tex with the size of the emulation check and the share of missed lookups among keys
without separators. The code is the corresponding part of the study's original numbers script.
Usage: python3 src/r4_numbers.py OUTDIR
"""
import csv, json, pathlib, random, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DB = ROOT / "dbms"
OUT = pathlib.Path(sys.argv[1]).resolve()
OUT.mkdir(parents=True, exist_ok=True)


def fmt(x):
    return f"{x:,}" if isinstance(x, int) else str(x)


def pct(a, b, d=1):
    return f"{100 * a / b:.{d}f}"


N = {}
D = {k: json.load(open(DB / f"results/dbms_results_{k}.json")) for k in ("synthetic", "dictionary")}
SEP = re.compile(r"[ \-_./']")
for k, tag in (("synthetic", "Syn"), ("dictionary", "Dic")):
    rows = [r[1] for r in csv.reader(open(DB / f"results/raw_{k}/dataset.csv"))]
    keys = random.Random(20261001 + 1).sample(rows, 20000)
    d = D[k]["drift"]["libc_en"]
    assert d["seq_point_hits"] - d["index_point_hits"] == len(d["missed_keys"])
    ms = set(d["missed_keys"])
    plain = [x for x in keys if not SEP.search(x)]
    N[f"Rtwo{tag}PlainMissPct"] = pct(sum(x in ms for x in plain), len(plain))
em = json.load(open(DB / "results/emulation/emulation_check.json"))
assert all(em[x]["real227_equals_emulated227"] and em[x]["positions_differing_228_vs_243"] == 0 for x in em)
N["RtwoEmulN"] = sum(em[x]["n"] for x in em)
with open(OUT / "numbers_r4.tex", "w", encoding="utf-8") as fh:
    fh.write("% Generated by src/r4_numbers.py from dbms/results. Do not edit.\n")
    for k in sorted(N):
        fh.write(f"\\providecommand{{\\{k}}}{{{fmt(N[k])}}}\n")
